"""New operator features on the synthetic review server; no real Docker or AI mutations."""
import argparse,json,time,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--out',required=True);args=parser.parse_args()
    out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    result={'checks':[],'console_errors':[],'screenshots':[]}
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True)
        context=browser.new_context(viewport={'width':1488,'height':1056},permissions=['clipboard-read','clipboard-write'])
        page=context.new_page()
        page.on('pageerror',lambda error:result['console_errors'].append(str(error)))
        def shot(name):page.screenshot(path=str(out/name));result['screenshots'].append(name)
        def navigate(view,title):
            page.goto('http://127.0.0.1:8790/#'+view)
            expect(page.get_by_role('heading',name=title,exact=True)).to_be_visible(timeout=15000)
            expect(page.locator('.loading')).to_have_count(0)
        def passed(name):result['checks'].append(name)
        page.goto('http://127.0.0.1:8790/login?lang=EN')
        page.get_by_label('Username',exact=True).fill('review-admin')
        page.get_by_label('Password',exact=True).fill('Review-only-password-4488')
        page.get_by_role('button',name='Open DCC Web').click()
        expect(page.locator('#language-switch')).to_be_visible()
        page.locator('#language-switch [data-language="EN"]').click()
        expect(page.get_by_role('heading',name='Overview',exact=True)).to_be_visible()
        page.reload();expect(page.get_by_role('heading',name='Overview',exact=True)).to_be_visible()
        expect(page.locator('.host-data')).to_contain_text('127.0.0.1:8790')
        passed('English interface and saved language after reload')
        navigate('containers','Containers')
        expect(page.locator('[data-container-host-address]')).to_contain_text('Host: 127.0.0.1:8790')
        page.locator('#container-grouping').select_option('none')
        names=page.locator('#containers-table tbody td.name button')
        expect(names.nth(0)).to_have_text('dcc-container-updater')
        page.locator('[data-sort=cpu]').click()
        expect(page.locator('#containers-table thead th').nth(6)).to_have_attribute('aria-sort','descending')
        expect(page.locator('#containers-table tbody td.name button').nth(0)).to_have_text('jellyfin')
        page.locator('[data-sort=cpu]').click()
        expect(page.locator('#containers-table thead th').nth(6)).to_have_attribute('aria-sort','ascending')
        expect(page.locator('#containers-table tbody td.name button').nth(0)).to_have_text('redis')
        page.locator('[data-sort=cpu]').click()
        expect(page.locator('#containers-table thead th').nth(6)).to_have_attribute('aria-sort','none')
        page.locator('[data-sort=ram]').click()
        expect(page.locator('#containers-table tbody td.name button').nth(0)).to_have_text('jellyfin')
        passed('Container view shows the active host endpoint inline and cycles CPU/RAM sorting through default, descending and ascending')
        expect(page.locator('#containers-table')).to_contain_text('Ports / panels')
        link=page.locator('#containers-table .panel-link').first
        assert link.get_attribute('target')=='_blank'
        assert 'noopener' in link.get_attribute('rel')
        panel_url=link.get_attribute('href')
        context.route(panel_url.rstrip('/')+'/**',lambda route:route.fulfill(status=200,body='Synthetic panel route; no user panel contacted'))
        with context.expect_page() as popup:link.click()
        panel=popup.value;panel.wait_for_url(panel_url.rstrip('/')+'/**',timeout=5000);assert panel.url.startswith(panel_url);panel.close()
        page.locator('[data-select]').nth(0).check();page.locator('[data-select]').nth(1).check()
        expect(page.locator('[data-bulk=stop]')).to_be_enabled()
        shot('containers-english-panels.png')
        page.locator('[data-bulk=stop]').click()
        expect(page.locator('#modal')).to_contain_text('Confirm operation')
        page.locator('#modal input[type=checkbox]').check()
        page.locator('#modal button[type=submit]').click()
        expect(page.locator('#toast')).to_contain_text('Operation completed',timeout=10000)
        passed('Published endpoint opens a safe new tab; confirmed bulk stop of two synthetic containers')
        page.locator('[data-actions]').first.click()
        expect(page.locator('#modal optgroup[label="Lifecycle"]')).to_have_count(1)
        expect(page.locator('#modal optgroup[label="Configuration"]')).to_have_count(1)
        expect(page.locator('#modal')).to_contain_text('Copy ports')
        shot('container-actions-english.png')
        page.locator('#modal select[name=action]').select_option('copy-ports')
        page.locator('#modal button[type=submit]').click()
        expect(page.locator('#toast')).to_contain_text('Copied to clipboard')
        passed('Categorized desktop-style container menu and port clipboard action')
        page.locator('[data-actions]').nth(1).click()
        page.locator('#modal select[name=action]').select_option('configure')
        page.locator('#modal button[type=submit]').click()
        expect(page.locator('#modal')).to_contain_text('Restart policy')
        expect(page.locator('#modal')).to_contain_text('AI configuration assistant')
        shot('edit-container-english.png')
        page.locator('#modal [data-close]').first.click()
        passed('Existing container editor exposes ports, restart and AI assistance')
        navigate('images','Docker images')
        details=page.locator('[data-inspect]').first
        expect(details).to_have_text('Details')
        box=details.bounding_box();assert box['x']+box['width']<=1488
        assert details.evaluate('(el)=>el.scrollWidth<=el.clientWidth')
        shot('images-actions-english.png')
        passed('Image Details action stays visible without clipped text')
        navigate('ai','AI assistant')
        expect(page.get_by_role('combobox',name='Provider',exact=True)).to_be_visible()
        expect(page.get_by_label('API base URL',exact=True)).to_be_visible()
        expect(page.get_by_label('Model',exact=True)).to_be_visible()
        shot('ai-connection-english.png')
        navigate('containers','Containers')
        page.locator('#new-container').click()
        expect(page.locator('#modal')).to_contain_text('AI configuration assistant')
        page.locator('#modal [name=ai_prompt]').fill('Prepare a test application and choose an available host port')
        page.locator('#modal [data-ai-generate]').click()
        expect(page.locator('#modal [data-ai-apply]')).to_be_visible(timeout=10000)
        page.locator('#modal [data-ai-apply]').click()
        expect(page.locator('#modal [name=name]')).to_have_value('fixture-ai-app')
        expect(page.locator('#modal [name=host_port]')).to_have_value('8789')
        shot('ai-container-proposal.png')
        page.locator('#modal [data-close]').first.click()
        passed('AI provider controls and explicit proposal-to-form application with port conflict resolution')
        navigate('mcp','AI / MCP')
        for unlimited in (False,True):
            page.locator('#grant-create').click()
            page.locator('#modal [name=name]').fill('Extended browser fixture')
            page.locator('#modal [name=days]').fill('2000')
            if unlimited:page.locator('#modal [name=unlimited]').check()
            page.locator('#modal input[name=profiles]').first.check()
            page.locator('#modal button[type=submit]').click()
            expect(page.locator('#modal')).to_contain_text('Token — shown once')
            page.locator('#modal [data-close]').first.click()
        navigate('mcp','AI / MCP')
        expect(page.locator('#content')).to_contain_text('No expiry')
        passed('MCP grant creation for 2000 days and unlimited access')
        untranslated={}
        for view,title in [('profiles','Connection profiles'),('settings','Settings'),('store','App Store'),('monitoring','Monitoring'),('logs','Logs and diagnostics'),('volumes','Volumes'),('networks','Networks'),('compose','Docker Compose'),('audit','Audit log')]:
            navigate(view,title)
            captions=page.locator('h1,h2,h3,th,label,summary,.page-heading p,button:not(.app-tile)').all_text_contents()
            remaining=[v.strip() for v in captions if re.search('[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]',v) and v.strip()]
            if remaining:untranslated[view]=remaining
        assert not untranslated,untranslated
        passed('English headings across every operational view')
        page.locator('#language-switch [data-language="PL"]').click()
        expect(page.get_by_role('heading',name='Dziennik operacji',exact=True)).to_be_visible()
        page.reload();expect(page.get_by_role('heading',name='Dziennik operacji',exact=True)).to_be_visible()
        navigate('containers','Kontenery');shot('containers-polish-panels.png')
        page.set_viewport_size({'width':390,'height':844})
        page.wait_for_timeout(220)
        assert page.locator('#sidebar').evaluate('(el)=>el.getBoundingClientRect().right<=1')
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        shot('mobile-container-actions.png')
        passed('Polish language persistence and mobile layout without page overflow')
        assert not result['console_errors'],result['console_errors']
        browser.close()
    (out/'browser-extended-results.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
